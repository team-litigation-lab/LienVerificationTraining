#!/usr/bin/env python3
"""Build js/cs-decks.js, the course's lesson decks, from the deck folders.

Each lesson deck holds only its most important slides; the full decks are PDF handouts in handouts/.

decks/<deck>/NN.webp     one image per slide (1280x720), in lesson order
decks/<deck>/text.json   the text on each slide, in order (its first line is the slide's title)
decks/<deck>/notes.json  the presenter's speaker notes, one per slide (shown in 🖥 Presenter view)
decks/<deck>/deck.json   { title, sections: [[first, last, heading], …],
                           sources: [{src, n}, …]  (where each slide comes from: its full deck and slide number),
                           titles: [title or null, …]  (a slide's own title, where its text alone doesn't give one),
                           handouts: {src: "/handouts/<file>.pdf"} }

Run after changing a deck:  python3 decks/build_decks.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The full decks the key slides come from, as the trainee sees them named (their PDFs are in handouts/).
SOURCE_NAMES = {
    "hs1": "Health Insurance Subrogation Training · Day 1",
    "hs2": "Health Insurance Subrogation Training · Day 2",
    "hs3": "Health Insurance Subrogation Training · Day 3",
    "hs4": "Health Insurance Subrogation Training · Day 4",
    "hs5": "Health Insurance Subrogation Training · Day 5",
    "lv2": "Medical Lien Balance Verification Training · Day 2",
    "lv3": "Medical Lien Balance Verification Training · Day 3",
    "liens": "Liens, Lien Holders & Reductions",
    "ln1": "The Lien Negotiator Role · Part 1",
    "ln2": "The Lien Negotiator Role · Part 2: ERISA & Government Plans",
    "lv1": "Medical Lien Balance Verification Training · Day 1",
    "erisa": "ERISA & Government Plan Liens",
}
# headers repeated on every slide of a deck, which aren't a slide's own title
SKIP = {"hi subro work flow", "fundamentals", "step by step guide"}


def clean(raw):
    """The slide's lines, without the reader's "Page n of N." label, repeated lines or repeated headers."""
    seen, lines = set(), []
    for line in raw.splitlines():
        line = re.sub(r"\s+", " ", line).strip()
        if not line or re.fullmatch(r"Page \d+ of \d+\.", line) or line.lower() in SKIP:
            continue
        if line.lower() in seen:
            continue
        seen.add(line.lower())
        lines.append(line)
    return lines


def title_of(lines, section):
    if not lines:
        return section, 0
    t, k = lines[0], 1
    # a cover or heading split over short lines ("THE LIEN" / "NEGOTIATOR ROLE", "After Bills Have" / "Been Submitted")
    while len(t.split()) <= 4 and k < len(lines) and k <= 2 and len(lines[k].split()) <= 4 and lines[k][:1].isupper() and not t.endswith((".", ":", "?")):
        t, k = f"{t} {lines[k]}", k + 1
    return t[:120], k


def main():
    out = {}
    for spec_file in sorted((ROOT / "decks").glob("*/deck.json")):
        folder, deck = spec_file.parent, spec_file.parent.name
        spec = json.loads(spec_file.read_text(encoding="utf-8"))
        texts = json.loads((folder / "text.json").read_text(encoding="utf-8"))
        notes_file = folder / "notes.json"   # the presenter's speaker notes, one per slide (optional)
        notes = json.loads(notes_file.read_text(encoding="utf-8")) if notes_file.exists() else [""] * len(texts)
        if len(notes) != len(texts):
            raise SystemExit(f"{deck}: {len(notes)} speaker notes for {len(texts)} slides")
        images = sorted(folder.glob("*.webp"))
        if not (len(images) == len(texts) == len(spec["sources"])):
            raise SystemExit(f"{deck}: {len(images)} images, {len(texts)} slide texts, {len(spec['sources'])} sources")
        slides = []
        for n, raw in enumerate(texts, start=1):
            sec = next((h for a, b, h in spec["sections"] if a <= n <= b), "")
            lines = clean(raw)
            given = (spec.get("titles") or [None] * len(texts))[n - 1]
            if given:   # the slide's title as written in deck.json; its text is the rest
                title, used = given, (1 if lines and lines[0] == given else 0)
            else:
                title, used = title_of(lines, sec)
            src = spec["sources"][n - 1]
            slides.append({"n": n, "img": f"/decks/{deck}/{n:02d}.webp", "title": title, "section": sec, "text": lines[used:],
                           "from": f"{SOURCE_NAMES.get(src['src'], src['src'])}, slide {src['n']}",
                           "handout": spec.get("handouts", {}).get(src["src"], ""), "notes": notes[n - 1]})
        out[deck] = {"title": spec["title"], "slides": slides}
    js = ("/* GENERATED by decks/build_decks.py from decks/<deck>/ (NN.webp, text.json, deck.json). Do not edit by hand.\n"
          "   CS_DECKS: deck id -> its title and slides ({ n, img, title, section, text, from, handout, notes }), shown by a \"slides\" module.\n"
          "   A lesson deck holds the most important slides; \"from\" names the full deck and slide, \"handout\" is its PDF. */\n"
          "window.CS_DECKS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    (ROOT / "js" / "cs-decks.js").write_text(js, encoding="utf-8")
    print("built js/cs-decks.js:", ", ".join(f"{k} ({len(v['slides'])} slides)" for k, v in out.items()))


if __name__ == "__main__":
    main()
